UPDATE IMDB_MOVIES
SET GENRE = 'UNKNOWN'
WHERE GENRE IS NULL;


## 3.	Top-Revenue generated movies based on each country.
SELECT * FROM 
(
    SELECT NAMES, DATE_X, SCORE, GENRE, OVERVIEW, CREW, ORIG_TITLE, STATUS, ORIG_LANG, BUDGET_X, REVENUE, COUNTRY,
            ROW_NUMBER() OVER (PARTITION BY COUNTRY ORDER BY BUDGET_X DESC) AS RANKING_BY_BUDGET_PER_COUNTRY
    FROM IMDB_MOVIES) 
WHERE RANKING_BY_BUDGET_PER_COUNTRY <=3
ORDER BY COUNTRY, RANKING_BY_BUDGET_PER_COUNTRY ASC;

## 4. Analyze decade-wise trends in movie production.

SELECT 
    FLOOR(EXTRACT(YEAR FROM DATE_X) / 10) * 10 AS DECADE,
    COUNT(*) AS MOVIECOUNT
FROM IMDB_MOVIES
GROUP BY FLOOR(EXTRACT(YEAR FROM DATE_X) / 10) * 10
ORDER BY MOVIECOUNT DESC;

## 5. Rolling 5-Year Budget Analysis for Movie Trends.

SELECT 
    	EXTRACT(YEAR FROM DATE_X) AS YEAR, 
AVG(BUDGET_X) OVER (ORDER BY EXTRACT(YEAR FROM DATE_X) ROWS BETWEEN 4 PRECEDING AND CURRENT ROW) AS ROLLINGAVGBUDGET
FROM IMDB_MOVIES;

## 6. Most popular genres by frequency.

SELECT 
    GENRE, 
    COUNT(*) AS GENRECOUNT
FROM IMDB_MOVIES
GROUP BY GENRE
ORDER BY GENRECOUNT DESC;


## 7. Top 10 movies by rating.

SELECT 
    NAMES, 
    SCORE
FROM IMDB_MOVIES
ORDER BY SCORE DESC
LIMIT 10;

## 8. Cumulative Revenue for each country

SELECT 
    COUNTRY,
    NAMES AS MOVIE_NAME,
    REVENUE AS REVENUE,
    SUM(REVENUE) OVER (PARTITION BY COUNTRY ORDER BY REVENUE ASC) AS CUMULATIVE_REVENUE
FROM 
    IMDB_MOVIES
ORDER BY 
    COUNTRY, REVENUE, CUMULATIVE_REVENUE DESC;


