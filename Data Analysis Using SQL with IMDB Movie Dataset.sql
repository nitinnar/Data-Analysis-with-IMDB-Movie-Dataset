##1. To Identify any duplicate records

SELECT * FROM
(
SELECT NAMES, DATE_X, SCORE, GENRE, OVERVIEW, CREW, ORIG_TITLE, STATUS, ORIG_LANG, BUDGET_X, REVENUE, COUNTRY, 
ROW_NUMBER() OVER(PARTITION BY NAMES, DATE_X, SCORE, GENRE, OVERVIEW, CREW, ORIG_TITLE, STATUS, ORIG_LANG, BUDGET_X, REVENUE, COUNTRY ORDER BY DATE_X ASC) AS DUPLICATE_IDENTIFICATION
    FROM IMDB_MOVIES)
WHERE DUPLICATE_IDENTIFICATION > 1;
	
